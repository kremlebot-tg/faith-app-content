def replace_in_payload(payload: dict, replacements: dict[tuple[int, int], dict]) -> int:
    changed = 0
    by_number = {chapter["number"]: chapter for chapter in payload["chapters"]}
    for (number, index), exercise in replacements.items():
        chapter = by_number.get(number)
        if chapter is None:
            continue
        chapter["test"][index] = exercise
        changed += 1
    return changed


def write_json(path: Path, payload: dict) -> None:
    path.write_text(
        json.dumps(payload, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )


def main() -> None:
    for book_id, replacements in REPLACEMENTS.items():
        target = ROOT / "content_tests" / f"{book_id}.json"
        payload = json.loads(target.read_text(encoding="utf-8"))
        changed = replace_in_payload(payload, replacements)
        if changed != len(replacements):
            raise SystemExit(
                f"{book_id}: заменено {changed} из {len(replacements)} заданий"
            )
        write_json(target, payload)

        draft_changes = 0
        for draft in sorted((ROOT / "content_tests" / "drafts").glob(f"{book_id}_*.json")):
            draft_payload = json.loads(draft.read_text(encoding="utf-8"))
            count = replace_in_payload(draft_payload, replacements)
            if count:
                write_json(draft, draft_payload)
                draft_changes += count
        print(
            f"{book_id}: exercises={changed} draft_exercises={draft_changes}"
        )


if __name__ == "__main__":
    main()
