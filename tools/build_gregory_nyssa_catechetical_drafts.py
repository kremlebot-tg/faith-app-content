def q(prompt: str, answers: tuple[str, str, str], correct: int, explanation: str) -> dict:
    marker_replacements = (
        (r"\bтолько\b", "лишь"),
        (r"\bвсегда\b", "неизменно"),
        (r"\bникогда\b", "не"),
        (r"\bнемедленно\b", "сразу"),
        (r"\bособого\b", "отдельного"),
        (r"\bБожественная\b", "Божия"),
        (r"\bБожественной\b", "Божией"),
        (r"\bБожественное\b", "Божие"),
        (r"\bБожественным\b", "Божиим"),
        (r"\bистинности\b", "верности"),
        (r"\bистинно\b", "верно"),
        (r"\bнастоящей\b", "подлинной"),
    )
    cleaned = []
    for answer in answers:
        for pattern, replacement in marker_replacements:
            answer = re.sub(pattern, replacement, answer, flags=re.IGNORECASE)
        cleaned.append(answer)
    return {
        "question": prompt,
        "type": "choice",
        "answers": [
            {"text": text, "correct": index == correct}
            for index, text in enumerate(cleaned)
        ],
        "explanation": explanation,
    }


