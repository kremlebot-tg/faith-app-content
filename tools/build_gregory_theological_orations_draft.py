def q(prompt: str, answers: tuple[str, str, str], correct: int, explanation: str) -> dict:
    return {
        "question": prompt,
        "type": "choice",
        "answers": [
            {"text": text, "correct": index == correct}
            for index, text in enumerate(answers)
        ],
        "explanation": explanation,
    }


def matching(prompt: str, pairs: tuple[tuple[str, str], ...], explanation: str) -> dict:
    return {
        "question": prompt,
        "type": "matching",
        "pairs": [{"left": left, "right": right} for left, right in pairs],
        "explanation": explanation,
    }


def ordering(prompt: str, items: tuple[str, ...], explanation: str) -> dict:
    return {
        "question": prompt,
        "type": "ordering",
        "items": list(items),
        "explanation": explanation,
    }


def cloze(
    question: str,
    prompt: str,
    answers: tuple[str, str, str],
    correct: int,
    explanation: str,
) -> dict:
    return {
        "question": question,
        "type": "cloze",
        "prompt": prompt,
        "answers": [
            {"text": text, "correct": index == correct}
            for index, text in enumerate(answers)
        ],
        "explanation": explanation,
    }


