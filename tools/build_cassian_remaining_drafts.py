def main() -> None:
    drafts = ROOT / "content_tests" / "drafts"
    drafts.mkdir(parents=True, exist_ok=True)
    for book_id, config in BOOKS.items():
        chapters = config["chapters"]
        if len(chapters) != 7:
            raise SystemExit(f"{book_id}: ожидалось 7 собеседований")
        payload = {
            "book_id": book_id,
            "status": "draft",
            "source": config["source"],
            "chapters": [
                {"number": number, "test": chapters[number - 1]}
                for number in range(1, 8)
            ],
        }
        output = drafts / f"{book_id}_01_07.json"
        output.write_text(
            json.dumps(payload, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
        )
        print(f"Wrote {output}: chapters=7 questions=21")


if __name__ == "__main__":
    main()
